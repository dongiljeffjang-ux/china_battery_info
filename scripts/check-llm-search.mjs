import assert from 'node:assert/strict';
process.env.DEEPSEEK_API_KEY = 'test-only';
process.env.SUPABASE_URL = 'https://example.supabase.co';
process.env.SUPABASE_SERVICE_ROLE_KEY = 'test-only';
process.env.LANGSMITH_TRACING = 'false';
delete process.env.DEEPSEEK_CAPTURE_RAW;
const { createJsonResponse } = await import('../lib/llm-provider.js');
const logs = [];
const providerRequests = [];
let output = [];
globalThis.fetch = async (url, options) => {
  if (url.includes('supabase.co')) {
    logs.push(JSON.parse(options.body));
    return new Response(null, { status: 204 });
  }
  providerRequests.push(JSON.parse(options.body));
  return Response.json({ status: 'completed', output, usage: { input_tokens: 100, output_tokens: 25 } });
};
const options = { provider: 'deepseek', webSearch: true, name: 'search_test', schema: {}, input: 'test' };
output = [{ type: 'web_search_call', status: 'completed' }];
await assert.rejects(createJsonResponse(options), /EMPTY_OUTPUT/);
assert.equal(logs.at(-1).payload.usage.input_tokens, 100);
assert.equal(logs.at(-1).status, 'failed');
const message = { type: 'message', content: [{ type: 'output_text', text: '{"articles":[]}' }] };
output = [message];
await assert.rejects(createJsonResponse(options), /SEARCH_NOT_EXECUTED/);
const capturesBeforeSuccess = logs.filter(row => row.payload.kind === 'search_response_raw').length;
output = [{ type: 'web_search_call', status: 'completed' }, message];
const result = await createJsonResponse(options);
assert.equal(providerRequests.at(-1).tool_choice, 'required', 'DeepSeek discovery must require at least one web search call');
assert.equal(providerRequests.at(-1).text, undefined, 'DeepSeek web search must not combine required tools with strict JSON schema');
assert.equal(result.telemetry.search_calls, 1);
assert.equal(logs.at(-1).status, 'ok');
assert.equal(logs.filter(row => row.payload.kind === 'search_response_raw').length, capturesBeforeSuccess, 'successful searches are not captured');
output = [{ type: 'web_search_call', status: 'completed' }, { type: 'message', content: [{ type: 'output_text', text: '검증된 기사를 선정하겠습니다.\n{"articles":[]}\n완료' }] }];
assert.deepEqual((await createJsonResponse(options)).data, { articles: [] });
const invalid = { type: 'message', content: [{ type: 'output_text', text: '宁德时代 https://example.com/news not JSON' }] };
output = [{ type: 'web_search_call', status: 'completed' }, invalid];
await assert.rejects(createJsonResponse(options), /INVALID_JSON_OUTPUT/);
const capture = logs.filter(row => row.payload.kind === 'search_response_raw').at(-1).payload;
assert.deepEqual(JSON.parse(capture.raw).output, output);
assert.equal(capture.raw.includes('test-only'), false);
console.log('LLM search telemetry checks passed (no paid API calls)');
